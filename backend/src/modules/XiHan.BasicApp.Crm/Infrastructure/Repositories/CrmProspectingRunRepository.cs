namespace XiHan.BasicApp.Crm.Infrastructure.Repositories;

public sealed class CrmProspectingRunRepository(ISqlSugarClientResolver clientResolver)
    : SaasRepository<SysCrmProspectingRun>(clientResolver), ICrmProspectingRunRepository
{
    private const int MaxFailureSummaryLength = 2000;

    private static string? BoundFailureSummary(string? summary)
        => summary is { Length: > MaxFailureSummaryLength } ? summary[..MaxFailureSummaryLength] : summary;

    public async Task<SysCrmProspectingRun?> GetByRequestKeyAsync(string requestKey, CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(requestKey);
        cancellationToken.ThrowIfCancellationRequested();
        var rows = await CreateQueryable()
            .Where(run => run.RequestKey == requestKey)
            .Take(2)
            .ToListAsync(cancellationToken);
        if (rows.Count > 1)
            throw new InvalidOperationException("The tenant contains multiple Runs for one idempotency key; the unique-key invariant is broken.");
        return rows.FirstOrDefault();
    }

    /// <summary>
    /// Atomically claims a queued Run or takes over a Run whose persisted lease has expired.
    /// The database clock is authoritative; the returned row contains the token and fencing version
    /// generated by the same UPDATE statement.
    /// </summary>
    public async Task<SysCrmProspectingRun?> TryClaimLeaseAsync(
        long runId,
        string leaseOwner,
        TimeSpan leaseDuration,
        CancellationToken cancellationToken = default)
    {
        if (runId <= 0) throw new ArgumentOutOfRangeException(nameof(runId));
        ArgumentException.ThrowIfNullOrWhiteSpace(leaseOwner);
        if (leaseOwner.Length > 160) throw new ArgumentOutOfRangeException(nameof(leaseOwner));
        if (leaseDuration <= TimeSpan.Zero || leaseDuration > TimeSpan.FromHours(1))
            throw new ArgumentOutOfRangeException(nameof(leaseDuration), "Lease duration must be greater than zero and at most one hour.");
        cancellationToken.ThrowIfCancellationRequested();

        var client = DbClient;
        if (client.CurrentConnectionConfig.DbType != DbType.PostgreSQL)
            throw new NotSupportedException("Prospecting lease claims require PostgreSQL.");

        // Match the framework's platform-tenant convention while never issuing an unscoped write.
        var tenantId = AsyncLocalCurrentTenantAccessor.Instance.Current?.TenantId ?? 0L;
        var leaseToken = Guid.NewGuid();
        var durationMilliseconds = checked((long)Math.Ceiling(leaseDuration.TotalMilliseconds));

        // One statement both arbitrates ownership and returns the exact row modified.
        // A legacy Running row with NULL expiry is deliberately not taken over.
        const string sql = """
            WITH lease_clock AS MATERIALIZED (
                SELECT clock_timestamp() AS now
            )
            UPDATE crm_prospecting_run AS run
            SET status = @runningStatus,
                started_at = lease_clock.now,
                completed_at = NULL,
                failure_summary = NULL,
                lease_owner = @leaseOwner,
                lease_token = @leaseToken,
                lease_heartbeat_at = lease_clock.now,
                lease_expires_at = lease_clock.now + (@leaseDurationMilliseconds * INTERVAL '1 millisecond'),
                fencing_version = run.fencing_version + 1
            FROM lease_clock
            WHERE run.tenant_id = @tenantId
              AND run.basic_id = @runId
              AND (
                    run.status = @queuedStatus
                    OR (
                        run.status = @runningStatus
                        AND run.lease_expires_at IS NOT NULL
                        AND run.lease_expires_at <= lease_clock.now
                    )
              )
            RETURNING run.*;
            """;

        var rows = await client.Ado.SqlQueryAsync<SysCrmProspectingRun>(
            sql,
            new SugarParameter("@tenantId", tenantId),
            new SugarParameter("@runId", runId),
            new SugarParameter("@leaseOwner", leaseOwner),
            new SugarParameter("@leaseToken", leaseToken),
            new SugarParameter("@leaseDurationMilliseconds", durationMilliseconds),
            new SugarParameter("@queuedStatus", (int)CrmProspectingRunStatus.Queued),
            new SugarParameter("@runningStatus", (int)CrmProspectingRunStatus.Running));

        return rows.SingleOrDefault();
    }

    /// <summary>
    /// Locks and validates the current live lease for the duration of the caller's transactional UnitOfWork.
    /// Child Candidate/Evidence/Score writes must execute on this same transaction after this method succeeds.
    /// </summary>
    public async Task<bool> TryLockLeaseForWriteAsync(
        long runId,
        Guid leaseToken,
        long fencingVersion,
        CancellationToken cancellationToken = default)
    {
        if (runId <= 0) throw new ArgumentOutOfRangeException(nameof(runId));
        if (leaseToken == Guid.Empty) throw new ArgumentException("Lease token cannot be empty.", nameof(leaseToken));
        if (fencingVersion <= 0) throw new ArgumentOutOfRangeException(nameof(fencingVersion));
        cancellationToken.ThrowIfCancellationRequested();

        var client = DbClient;
        if (client.CurrentConnectionConfig.DbType != DbType.PostgreSQL)
            throw new NotSupportedException("Prospecting write fencing requires PostgreSQL.");
        if (client.Ado.Transaction is null)
            throw new InvalidOperationException("Prospecting write fencing must run inside an active transactional UnitOfWork.");

        var tenantId = AsyncLocalCurrentTenantAccessor.Instance.Current?.TenantId ?? 0L;
        const string sql = """
            SELECT run.basic_id AS "BasicId"
            FROM crm_prospecting_run AS run
            WHERE run.tenant_id = @tenantId
              AND run.basic_id = @runId
              AND run.status = @runningStatus
              AND run.lease_token = @leaseToken
              AND run.fencing_version = @fencingVersion
              AND run.lease_expires_at IS NOT NULL
              AND run.lease_expires_at > clock_timestamp()
            FOR UPDATE;
            """;

        var rows = await client.Ado.SqlQueryAsync<long>(
            sql,
            new SugarParameter("@tenantId", tenantId),
            new SugarParameter("@runId", runId),
            new SugarParameter("@runningStatus", (int)CrmProspectingRunStatus.Running),
            new SugarParameter("@leaseToken", leaseToken),
            new SugarParameter("@fencingVersion", fencingVersion));

        return rows.Count == 1;
    }

    public async Task<SysCrmProspectingRun?> ClaimQueuedAsync(
        long runId,
        DateTimeOffset startedAt,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        // Conditional update is the concurrency boundary: only one worker can move Queued -> Running.
        var claimed = await UpdateAsync(
            run => new SysCrmProspectingRun
            {
                Status = CrmProspectingRunStatus.Running,
                StartedAt = startedAt,
                CompletedAt = null,
                FailureSummary = null
            },
            run => run.BasicId == runId && run.Status == CrmProspectingRunStatus.Queued,
            cancellationToken);

        if (!claimed)
        {
            return null;
        }

        var rows = await CreateQueryable()
            .Where(run => run.BasicId == runId && run.Status == CrmProspectingRunStatus.Running)
            .Take(1)
            .ToListAsync(cancellationToken);

        return rows.FirstOrDefault();
    }

    /// <summary>
    /// Renews a live lease using PostgreSQL database time, never a timestamp supplied by the worker.
    /// A stale token/version or an already expired lease affects no rows.
    /// </summary>
    public async Task<bool> RenewLeaseWithDatabaseClockAsync(
        long runId,
        Guid leaseToken,
        long fencingVersion,
        TimeSpan leaseDuration,
        CancellationToken cancellationToken = default)
    {
        if (runId <= 0) throw new ArgumentOutOfRangeException(nameof(runId));
        if (leaseToken == Guid.Empty) throw new ArgumentException("Lease token cannot be empty.", nameof(leaseToken));
        if (fencingVersion <= 0) throw new ArgumentOutOfRangeException(nameof(fencingVersion));
        if (leaseDuration <= TimeSpan.Zero || leaseDuration > TimeSpan.FromHours(1))
            throw new ArgumentOutOfRangeException(nameof(leaseDuration), "Lease duration must be greater than zero and at most one hour.");
        cancellationToken.ThrowIfCancellationRequested();

        var client = DbClient;
        if (client.CurrentConnectionConfig.DbType != DbType.PostgreSQL)
            throw new NotSupportedException("Prospecting lease renewal requires PostgreSQL.");

        var tenantId = AsyncLocalCurrentTenantAccessor.Instance.Current?.TenantId ?? 0L;
        var durationMilliseconds = checked((long)Math.Ceiling(leaseDuration.TotalMilliseconds));
        const string sql = """
            WITH lease_clock AS MATERIALIZED (
                SELECT clock_timestamp() AS now
            )
            UPDATE crm_prospecting_run AS run
            SET lease_heartbeat_at = lease_clock.now,
                lease_expires_at = lease_clock.now + (@leaseDurationMilliseconds * INTERVAL '1 millisecond')
            FROM lease_clock
            WHERE run.tenant_id = @tenantId
              AND run.basic_id = @runId
              AND run.status = @runningStatus
              AND run.lease_token = @leaseToken
              AND run.fencing_version = @fencingVersion
              AND run.lease_expires_at IS NOT NULL
              AND run.lease_expires_at > lease_clock.now
            RETURNING run.basic_id AS "BasicId";
            """;

        var rows = await client.Ado.SqlQueryAsync<long>(
            sql,
            new SugarParameter("@tenantId", tenantId),
            new SugarParameter("@runId", runId),
            new SugarParameter("@runningStatus", (int)CrmProspectingRunStatus.Running),
            new SugarParameter("@leaseToken", leaseToken),
            new SugarParameter("@fencingVersion", fencingVersion),
            new SugarParameter("@leaseDurationMilliseconds", durationMilliseconds));

        return rows.Count == 1;
    }

    public async Task<bool> RenewLeaseAsync(
        long runId,
        Guid leaseToken,
        long fencingVersion,
        DateTimeOffset heartbeatAt,
        TimeSpan leaseDuration,
        CancellationToken cancellationToken = default)
    {
        if (runId <= 0) throw new ArgumentOutOfRangeException(nameof(runId));
        if (leaseToken == Guid.Empty) throw new ArgumentException("Lease token cannot be empty.", nameof(leaseToken));
        if (fencingVersion <= 0) throw new ArgumentOutOfRangeException(nameof(fencingVersion));
        if (leaseDuration <= TimeSpan.Zero || leaseDuration > TimeSpan.FromHours(1))
            throw new ArgumentOutOfRangeException(nameof(leaseDuration), "Lease duration must be greater than zero and at most one hour.");
        cancellationToken.ThrowIfCancellationRequested();

        return await UpdateAsync(
            run => new SysCrmProspectingRun
            {
                LeaseHeartbeatAt = heartbeatAt,
                LeaseExpiresAt = heartbeatAt.Add(leaseDuration)
            },
            run => run.BasicId == runId &&
                run.Status == CrmProspectingRunStatus.Running &&
                run.LeaseToken == leaseToken &&
                run.FencingVersion == fencingVersion &&
                run.LeaseExpiresAt != null &&
                run.LeaseExpiresAt > heartbeatAt,
            cancellationToken);
    }

    public async Task<bool> CompleteFencedAsync(
        long runId,
        Guid leaseToken,
        long fencingVersion,
        DateTimeOffset now,
        string rawResultsJson,
        int rawRecordCount,
        int failureCount,
        string? failureSummary,
        DateTimeOffset completedAt,
        CancellationToken cancellationToken = default,
        int candidateCount = 0)
    {
        if (runId <= 0) throw new ArgumentOutOfRangeException(nameof(runId));
        if (leaseToken == Guid.Empty) throw new ArgumentException("Lease token cannot be empty.", nameof(leaseToken));
        if (fencingVersion <= 0) throw new ArgumentOutOfRangeException(nameof(fencingVersion));
        ArgumentNullException.ThrowIfNull(rawResultsJson);
        if (rawRecordCount < 0 || candidateCount < 0 || failureCount < 0)
            throw new ArgumentOutOfRangeException(nameof(rawRecordCount));
        cancellationToken.ThrowIfCancellationRequested();

        var status = failureCount == 0
            ? CrmProspectingRunStatus.Succeeded
            : rawRecordCount > 0
                ? CrmProspectingRunStatus.PartiallySucceeded
                : CrmProspectingRunStatus.Failed;

        return await UpdateAsync(
            run => new SysCrmProspectingRun
            {
                Status = status,
                RawResultsJson = rawResultsJson,
                RawRecordCount = rawRecordCount,
                CandidateCount = candidateCount,
                FailureCount = failureCount,
                FailureSummary = BoundFailureSummary(failureSummary),
                CompletedAt = completedAt,
                LeaseOwner = null,
                LeaseToken = null,
                LeaseExpiresAt = null,
                LeaseHeartbeatAt = null
            },
            run => run.BasicId == runId &&
                run.Status == CrmProspectingRunStatus.Running &&
                run.LeaseToken == leaseToken &&
                run.FencingVersion == fencingVersion &&
                run.LeaseExpiresAt != null &&
                run.LeaseExpiresAt > now,
            cancellationToken);
    }

    public async Task<bool> CancelFencedAsync(
        long runId,
        Guid leaseToken,
        long fencingVersion,
        DateTimeOffset now,
        DateTimeOffset completedAt,
        CancellationToken cancellationToken = default)
    {
        if (runId <= 0) throw new ArgumentOutOfRangeException(nameof(runId));
        if (leaseToken == Guid.Empty) throw new ArgumentException("Lease token cannot be empty.", nameof(leaseToken));
        if (fencingVersion <= 0) throw new ArgumentOutOfRangeException(nameof(fencingVersion));
        cancellationToken.ThrowIfCancellationRequested();

        return await UpdateAsync(
            run => new SysCrmProspectingRun
            {
                Status = CrmProspectingRunStatus.Cancelled,
                CompletedAt = completedAt,
                LeaseOwner = null,
                LeaseToken = null,
                LeaseExpiresAt = null,
                LeaseHeartbeatAt = null
            },
            run => run.BasicId == runId &&
                run.Status == CrmProspectingRunStatus.CancelRequested &&
                run.LeaseToken == leaseToken &&
                run.FencingVersion == fencingVersion &&
                run.LeaseExpiresAt != null &&
                run.LeaseExpiresAt > now,
            cancellationToken);
    }

    public async Task<bool> FailFencedAsync(
        long runId,
        Guid leaseToken,
        long fencingVersion,
        DateTimeOffset now,
        string failureSummary,
        DateTimeOffset completedAt,
        CancellationToken cancellationToken = default)
    {
        if (runId <= 0) throw new ArgumentOutOfRangeException(nameof(runId));
        if (leaseToken == Guid.Empty) throw new ArgumentException("Lease token cannot be empty.", nameof(leaseToken));
        if (fencingVersion <= 0) throw new ArgumentOutOfRangeException(nameof(fencingVersion));
        ArgumentException.ThrowIfNullOrWhiteSpace(failureSummary);
        cancellationToken.ThrowIfCancellationRequested();

        return await UpdateAsync(
            run => new SysCrmProspectingRun
            {
                Status = CrmProspectingRunStatus.Failed,
                FailureCount = 1,
                FailureSummary = BoundFailureSummary(failureSummary),
                CompletedAt = completedAt,
                LeaseOwner = null,
                LeaseToken = null,
                LeaseExpiresAt = null,
                LeaseHeartbeatAt = null
            },
            run => run.BasicId == runId &&
                run.Status == CrmProspectingRunStatus.Running &&
                run.LeaseToken == leaseToken &&
                run.FencingVersion == fencingVersion &&
                run.LeaseExpiresAt != null &&
                run.LeaseExpiresAt > now,
            cancellationToken);
    }

    public async Task<IReadOnlyList<SysCrmProspectingRun>> GetLatestByCampaignAsync(long campaignId, int limit, CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();
        var take = Math.Clamp(limit, 1, 500);
        return await CreateQueryable()
            .Where(run => run.CampaignId == campaignId)
            .OrderByDescending(run => run.CreatedTime)
            .Take(take)
            .ToListAsync(cancellationToken);
    }

    public async Task<IReadOnlyList<long>> GetQueuedIdsAsync(CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        return await CreateQueryable()
            .Where(run => run.Status == CrmProspectingRunStatus.Queued)
            .OrderBy(run => run.CreatedTime)
            .Select(run => run.BasicId)
            .ToListAsync(cancellationToken);
    }

    public async Task<bool> RecoverInterruptedAsync(
        DateTimeOffset recoveredAt,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        // A crashed worker can safely be retried from the immutable strategy snapshot.
        var requeued = await UpdateAsync(
            run => new SysCrmProspectingRun
            {
                Status = CrmProspectingRunStatus.Queued,
                StartedAt = null
            },
            run => run.Status == CrmProspectingRunStatus.Running,
            cancellationToken);

        // Cancellation intent survives process death and must not be converted back to executable work.
        var cancelled = await UpdateAsync(
            run => new SysCrmProspectingRun
            {
                Status = CrmProspectingRunStatus.Cancelled,
                CompletedAt = recoveredAt
            },
            run => run.Status == CrmProspectingRunStatus.CancelRequested,
            cancellationToken);

        return requeued || cancelled;
    }

    public async Task<bool> CompleteAsync(
        long runId,
        string rawResultsJson,
        int rawRecordCount,
        int failureCount,
        string? failureSummary,
        DateTimeOffset completedAt,
        CancellationToken cancellationToken = default,
        int candidateCount = 0)
    {
        failureSummary = BoundFailureSummary(failureSummary);
        var status = failureCount == 0
            ? CrmProspectingRunStatus.Succeeded
            : rawRecordCount > 0
                ? CrmProspectingRunStatus.PartiallySucceeded
                : CrmProspectingRunStatus.Failed;

        var completed = await UpdateAsync(
            run => new SysCrmProspectingRun
            {
                Status = status,
                RawResultsJson = rawResultsJson,
                RawRecordCount = rawRecordCount,
                CandidateCount = candidateCount,
                FailureCount = failureCount,
                FailureSummary = failureSummary,
                CompletedAt = completedAt
            },
            run => run.BasicId == runId && run.Status == CrmProspectingRunStatus.Running,
            cancellationToken);
        if (completed) return true;

        // Cancellation wins if it changed Running to CancelRequested before completion.
        return await UpdateAsync(
            run => new SysCrmProspectingRun
            {
                Status = CrmProspectingRunStatus.Cancelled,
                RawResultsJson = rawResultsJson,
                RawRecordCount = rawRecordCount,
                CandidateCount = candidateCount,
                FailureCount = failureCount,
                FailureSummary = failureSummary,
                CompletedAt = completedAt
            },
            run => run.BasicId == runId && run.Status == CrmProspectingRunStatus.CancelRequested,
            cancellationToken);
    }

    public async Task<bool> FailAsync(
        long runId,
        string failureSummary,
        DateTimeOffset completedAt,
        CancellationToken cancellationToken = default)
    {
        failureSummary = BoundFailureSummary(failureSummary) ?? string.Empty;
        var failed = await UpdateAsync(
            run => new SysCrmProspectingRun
            {
                Status = CrmProspectingRunStatus.Failed,
                FailureCount = 1,
                FailureSummary = failureSummary,
                CompletedAt = completedAt
            },
            run => run.BasicId == runId && run.Status == CrmProspectingRunStatus.Running,
            cancellationToken);
        if (failed) return true;

        return await UpdateAsync(
            run => new SysCrmProspectingRun
            {
                Status = CrmProspectingRunStatus.Cancelled,
                CompletedAt = completedAt
            },
            run => run.BasicId == runId && run.Status == CrmProspectingRunStatus.CancelRequested,
            cancellationToken);
    }
}
